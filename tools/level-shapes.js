const THEMES = [FRUITS, PLANTS, ANIMALS, VEHICLES, ANIMALS2, FOOD, SEA, OBJECTS, SKY, MIX];

function shapeForLevel(id) {
  const d = Math.max(0, Math.min(THEMES.length - 1, Math.floor((id - 1) / 10)));
  const t = (id - 1) % 10;
  return THEMES[d][t % THEMES[d].length];
}

function stampShape(shape, cols, rows, flipX = false) {
  const mask = shape.mask;
  const mh = mask.length;
  const mw = mask[0].length;
  const scale = Math.min(cols / mw, rows / mh);
  const tw = mw * scale;
  const th = mh * scale;
  const ox = (cols - tw) / 2;
  const oy = (rows - th) / 2;
  const occ = new Array(cols * rows).fill(false);
  for (let y = 0; y < rows; y++) {
    for (let x = 0; x < cols; x++) {
      const x0 = (x - ox) / scale;
      const x1 = (x + 1 - ox) / scale;
      const y0 = (y - oy) / scale;
      const y1 = (y + 1 - oy) / scale;
      const ix0 = Math.max(0, Math.floor(x0));
      const ix1 = Math.min(mw, Math.ceil(x1));
      const iy0 = Math.max(0, Math.floor(y0));
      const iy1 = Math.min(mh, Math.ceil(y1));
      let filled = 0;
      let total = 0;
      for (let iy = iy0; iy < iy1; iy++) {
        for (let ix = ix0; ix < ix1; ix++) {
          total += 1;
          const mx = flipX ? mw - 1 - ix : ix;
          const my = mh - 1 - iy;
          if ((mask[my][mx] || '.') === '#') filled += 1;
        }
      }
      if (total > 0 && filled / total >= 0.38) occ[y * cols + x] = true;
    }
  }
  return occ;
}

function dilate(occ, cols, rows) {
  const next = occ.slice();
  for (let y = 0; y < rows; y++) {
    for (let x = 0; x < cols; x++) {
      if (occ[y * cols + x]) continue;
      const n =
        (x > 0 && occ[y * cols + x - 1])
        || (x + 1 < cols && occ[y * cols + x + 1])
        || (y > 0 && occ[(y - 1) * cols + x])
        || (y + 1 < rows && occ[(y + 1) * cols + x]);
      if (n) next[y * cols + x] = true;
    }
  }
  return next;
}

function keepLargest(occ, cols, rows) {
  const seen = new Uint8Array(occ.length);
  let best = [];
  for (let i = 0; i < occ.length; i++) {
    if (!occ[i] || seen[i]) continue;
    const stack = [i];
    const cells = [];
    seen[i] = 1;
    while (stack.length) {
      const cur = stack.pop();
      cells.push(cur);
      const x = cur % cols;
      const y = (cur / cols) | 0;
      const nbrs = [];
      if (x > 0) nbrs.push(cur - 1);
      if (x + 1 < cols) nbrs.push(cur + 1);
      if (y > 0) nbrs.push(cur - cols);
      if (y + 1 < rows) nbrs.push(cur + cols);
      for (const n of nbrs) {
        if (!occ[n] || seen[n]) continue;
        seen[n] = 1;
        stack.push(n);
      }
    }
    if (cells.length > best.length) best = cells;
  }
  if (!best.length) return occ;
  const out = new Array(occ.length).fill(false);
  for (const i of best) out[i] = true;
  return out;
}

function occupyShape(id, cols, rows) {
  const shape = shapeForLevel(id);
  const flip = Math.floor((id - 1) / 50) % 2 === 1;
  let occ = stampShape(shape, cols, rows, flip);
  occ = keepLargest(occ, cols, rows);
  let filled = occ.reduce((n, v) => n + (v ? 1 : 0), 0);
  const minFill = Math.max(56, Math.floor(cols * rows * 0.28));
  let grow = 0;
  while (filled < minFill && grow < 1) {
    occ = dilate(occ, cols, rows);
    occ = keepLargest(occ, cols, rows);
    filled = occ.reduce((n, v) => n + (v ? 1 : 0), 0);
    grow += 1;
  }
  return { occ, shape };
}

