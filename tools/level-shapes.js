'use strict';

/** Per-level wall silhouettes. Masks are top-row-first; '#' is a brick. */

function S(id, name, ...rows) {
  const w = Math.max(...rows.map((r) => r.length));
  return { id, name, mask: rows.map((r) => r.padEnd(w, '.')) };
}

function raster(id, name, w, h, fn) {
  const mask = [];
  for (let y = 0; y < h; y++) {
    let row = '';
    for (let x = 0; x < w; x++) {
      const u = w <= 1 ? 0 : (x / (w - 1)) * 2 - 1;
      const v = h <= 1 ? 0 : 1 - (y / (h - 1)) * 2;
      row += fn(u, v) ? '#' : '.';
    }
    mask.push(row);
  }
  return { id, name, mask };
}

function hypot2(x, y) {
  return Math.hypot(x, y);
}

